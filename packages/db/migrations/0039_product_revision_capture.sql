-- F22: transactional database-generated material-change history, reusing the
-- existing append-only table. No historical rows or purchase snapshots rewritten.
-- Pattern: invoker audit trigger. Technical/moderation bookkeeping is excluded;
-- nonpublic compliance/evidence values are redacted, not copied into history.
-- rollback: retain history; removing capture would reopen the audit gap. Any
-- reviewed application rollback can keep this additive trigger in place.
CREATE FUNCTION app.capture_material_product_revision() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
  old_data jsonb;
  new_data jsonb;
  fields text[];
  old_snapshot jsonb := '{}'::jsonb;
  new_snapshot jsonb := '{}'::jsonb;
  field text;
  visible_fields constant text[] := ARRAY[
    'seller_id','brand_id','master_product_id','name','name_en','sku','slug',
    'price_piastres','promo_price_piastres','volume_ml','stock','fulfilment_hours',
    'concentration','form','gender_positioning','scent_family','notes_top',
    'notes_heart','notes_base','seasons','day_night','occasions','projection_band',
    'longevity_band','performance_source','return_eligibility'
  ];
BEGIN
  old_data := to_jsonb(OLD) - ARRAY['id','created_at','updated_at','search_text',
    'status','moderation_notes','moderation_reason','submitted_at','moderated_at',
    'moderated_by','published_at'];
  new_data := to_jsonb(NEW) - ARRAY['id','created_at','updated_at','search_text',
    'status','moderation_notes','moderation_reason','submitted_at','moderated_at',
    'moderated_by','published_at'];
  SELECT array_agg(key ORDER BY key) INTO fields
    FROM jsonb_each(old_data) WHERE value IS DISTINCT FROM new_data->key;
  IF fields IS NULL THEN RETURN NEW; END IF;
  FOREACH field IN ARRAY fields LOOP
    IF field = ANY(visible_fields) THEN
      old_snapshot := old_snapshot || jsonb_build_object(field, old_data->field);
      new_snapshot := new_snapshot || jsonb_build_object(field, new_data->field);
    ELSE
      old_snapshot := old_snapshot || jsonb_build_object(field, jsonb_build_object('redacted',true));
      new_snapshot := new_snapshot || jsonb_build_object(field, jsonb_build_object('redacted',true));
    END IF;
  END LOOP;
  INSERT INTO public.product_revisions(product_id,changed_by,changed_fields,before,after)
    VALUES (NEW.id,app.actor_id(),fields,old_snapshot::text,new_snapshot::text);
  RETURN NEW;
END $$;
CREATE TRIGGER products_capture_material_revision AFTER UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION app.capture_material_product_revision();

-- A caller cannot manufacture a revision by writing the history table directly.
CREATE FUNCTION app.require_generated_product_revision() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
  IF pg_trigger_depth() < 2 THEN
    RAISE EXCEPTION 'Product revisions must be generated by a material product change'
      USING ERRCODE='insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER product_revisions_generated_only BEFORE INSERT ON product_revisions
  FOR EACH ROW EXECUTE FUNCTION app.require_generated_product_revision();
